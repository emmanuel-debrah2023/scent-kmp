package org.scent.project.data.remote.a2ui.schema

import kotlinx.serialization.ExperimentalSerializationApi
import kotlinx.serialization.descriptors.PrimitiveKind
import kotlinx.serialization.descriptors.SerialDescriptor
import kotlinx.serialization.descriptors.StructureKind
import kotlinx.serialization.descriptors.elementDescriptors
import kotlinx.serialization.json.Json
import kotlinx.serialization.json.JsonElement
import kotlinx.serialization.json.JsonObject
import kotlinx.serialization.json.JsonPrimitive
import kotlinx.serialization.json.buildJsonArray
import kotlinx.serialization.json.buildJsonObject
import kotlinx.serialization.json.put
import org.scent.project.data.remote.a2ui.catalog.SCENT_CATALOG_ID
import org.scent.project.data.remote.a2ui.catalog.ScentComponent
import org.scent.project.data.remote.a2ui.catalog.SchemaDescription

private const val FALLBACK_COMPONENT = "Unknown"
private val prettyJson = Json { prettyPrint = true }

// JSON Schema of the scent/v1 catalog, generated by walking the Kotlin descriptors so it can never
// drift from the types. Components follow the sealed descriptor's order and $defs are sorted, so the output is stable.
@OptIn(ExperimentalSerializationApi::class)
fun catalogSchema(): JsonObject {
    val defs = mutableMapOf<String, JsonElement>()
    val sealed = ScentComponent.serializer().descriptor
    val subclasses =
        sealed
            .getElementDescriptor(1)
            .elementDescriptors
            .filter { it.simpleName() != FALLBACK_COMPONENT }
    return buildJsonObject {
        put("catalogId", SCENT_CATALOG_ID)
        put(
            "components",
            buildJsonObject {
                subclasses.forEach { put(it.simpleName(), componentSchema(it, defs)) }
            },
        )
        put("\$defs", JsonObject(defs.entries.sortedBy { it.key }.associate { it.key to it.value }))
    }
}

fun catalogSchemaJson(): String = prettyJson.encodeToString(JsonObject.serializer(), catalogSchema())

@OptIn(ExperimentalSerializationApi::class)
private fun componentSchema(
    descriptor: SerialDescriptor,
    defs: MutableMap<String, JsonElement>,
): JsonObject =
    buildJsonObject {
        put("type", "object")
        put("properties", propertiesOf(descriptor, defs, constComponent = descriptor.simpleName()))
        put("required", buildJsonArray { add(JsonPrimitive("component")) })
    }

@OptIn(ExperimentalSerializationApi::class)
private fun propertiesOf(
    descriptor: SerialDescriptor,
    defs: MutableMap<String, JsonElement>,
    constComponent: String?,
): JsonObject =
    buildJsonObject {
        if (constComponent != null) put("component", buildJsonObject { put("const", constComponent) })
        for (i in 0 until descriptor.elementsCount) {
            val description =
                descriptor
                    .getElementAnnotations(i)
                    .filterIsInstance<SchemaDescription>()
                    .firstOrNull()
                    ?.text
            val schema = typeSchema(descriptor.getElementDescriptor(i), defs)
            put(
                descriptor.getElementName(i),
                if (description == null) schema else JsonObject(schema + ("description" to JsonPrimitive(description))),
            )
        }
    }

@OptIn(ExperimentalSerializationApi::class)
private fun typeSchema(
    descriptor: SerialDescriptor,
    defs: MutableMap<String, JsonElement>,
): JsonObject =
    when (descriptor.kind) {
        PrimitiveKind.STRING -> buildJsonObject { put("type", "string") }
        PrimitiveKind.BOOLEAN -> buildJsonObject { put("type", "boolean") }
        PrimitiveKind.INT, PrimitiveKind.LONG, PrimitiveKind.SHORT, PrimitiveKind.BYTE ->
            buildJsonObject { put("type", "integer") }
        PrimitiveKind.FLOAT, PrimitiveKind.DOUBLE -> buildJsonObject { put("type", "number") }
        StructureKind.LIST ->
            buildJsonObject {
                put("type", "array")
                put("items", typeSchema(descriptor.getElementDescriptor(0), defs))
            }
        StructureKind.MAP ->
            buildJsonObject {
                put("type", "object")
                put("additionalProperties", typeSchema(descriptor.getElementDescriptor(1), defs))
            }
        StructureKind.CLASS -> {
            val name = descriptor.simpleName()
            if (name !in defs) {
                defs[name] = JsonObject(emptyMap()) // reserve first so a recursive type terminates
                defs[name] =
                    buildJsonObject {
                        put("type", "object")
                        put("properties", propertiesOf(descriptor, defs, constComponent = null))
                    }
            }
            buildJsonObject { put("\$ref", "#/\$defs/$name") }
        }
        else -> error("Unsupported catalog type ${descriptor.serialName}: add it to the schema generator")
    }

private fun SerialDescriptor.simpleName(): String = serialName.removeSuffix("?").substringAfterLast('.')
